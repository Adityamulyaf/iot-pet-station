import { test, expect } from '@playwright/test';

test('local workspace connects to MQTT, controls a station, and handles late results', async ({ page }) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.status() >= 500) errors.push(`${response.status()} ${response.url()}`); });
    await page.goto('/login');
    await page.screenshot({ path: '../artifacts/login-desktop.png', fullPage: true });
    await page.getByLabel('Email', { exact: true }).fill('demo@petstation.local');
    await page.getByLabel('Kata sandi', { exact: true }).fill('petstation-local');
    await page.getByRole('button', { name: 'Masuk ke workspace' }).click();
    await expect(page.getByRole('heading', { name: 'Station saya', exact: true })).toBeVisible();
    await expect(page.locator('.station-card')).toHaveCount(2);
    await page.locator('.station-card').first().click();
    await expect(page.getByRole('heading', { name: 'Ringkasan station' })).toBeVisible();
    await expect(page.locator('.station-strip .badge')).toHaveText('Online');
    await expect(page.getByRole('button', { name: 'Beri pakan', exact: true })).toBeEnabled();
    await expect(page.locator('.metric-value').first()).not.toContainText('N/A');
    await page.screenshot({ path: '../artifacts/dashboard-desktop.png', fullPage: true });
    await page.getByRole('button', { name: 'Beri pakan', exact: true }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.getByRole('button', { name: 'Batal', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByRole('button', { name: 'Beri pakan', exact: true }).click();
    await page.getByRole('button', { name: 'Ya, kirim perintah' }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.locator('tbody tr').first()).toContainText('Selesai');
    await page.locator('tbody tr').first().getByRole('button').click();
    await expect(page.getByRole('dialog')).toContainText('2000 ms');
    await page.getByRole('button', { name: 'Tutup detail' }).click();
    await page.getByRole('link', { name: 'Pengaturan', exact: true }).click();
    await page.getByLabel('Nama station', { exact: true }).fill('Station ruang keluarga');
    await page.getByRole('button', { name: 'Simpan perubahan' }).click();
    await expect(page.getByRole('status')).toContainText('Pengaturan station disimpan.');
    await page.getByLabel('Kondisi simulator').selectOption('low_water');
    await page.getByRole('button', { name: 'Terapkan skenario' }).click();
    await expect(page.getByText('Skenario aktif: Air rendah.', { exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Dashboard', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Salurkan air', exact: true })).toBeDisabled();
    await expect(page.locator('.metric-value').nth(1)).toContainText('8');
    await page.getByRole('link', { name: 'Pengaturan', exact: true }).click();
    await page.getByLabel('Kondisi simulator').selectOption('delayed');
    await page.getByRole('button', { name: 'Terapkan skenario' }).click();
    await expect(page.getByText('Skenario aktif: Hasil terlambat.', { exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Dashboard', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Salurkan air', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: 'Salurkan air', exact: true }).click();
    await page.getByRole('button', { name: 'Ya, kirim perintah' }).click();
    await expect(page.locator('tbody tr').first()).toContainText('Timeout', { timeout: 40_000 });
    await expect(page.getByRole('button', { name: 'Beri pakan', exact: true })).toBeDisabled();
    await expect(page.locator('tbody tr').first()).toContainText('Hasil diterima terlambat', { timeout: 25_000 });
    await page.getByRole('link', { name: 'Pengaturan', exact: true }).click();
    await page.getByLabel('Kondisi simulator').selectOption('normal');
    await page.getByRole('button', { name: 'Terapkan skenario' }).click();
    await expect(page.getByText('Skenario aktif: Normal.', { exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Riwayat', exact: true }).click();
    await page.getByLabel('Tindakan', { exact: true }).selectOption('water');
    await expect(page.locator('tbody')).toContainText('Salurkan air');
    await expect(page.locator('tbody')).not.toContainText('Beri pakan');
    await page.getByRole('link', { name: 'Analytics', exact: true }).click();
    await expect(page.locator('canvas')).toBeVisible();
    await expect(page.locator('.chart-empty')).toBeHidden();
    await page.getByRole('button', { name: '7 hari', exact: true }).click();
    await expect(page.getByRole('button', { name: '7 hari', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await page.getByRole('link', { name: 'Dashboard', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await expect.poll(() => page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().right <= 0)).toBe(true);
    await page.screenshot({ path: '../artifacts/dashboard-mobile.png', fullPage: true });
    await page.getByRole('button', { name: 'Buka navigasi' }).click();
    await expect(page.getByRole('link', { name: 'Pengaturan', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Keluar', exact: true }).click();
    await expect(page).toHaveURL(/\/login$/);
    await page.screenshot({ path: '../artifacts/login-mobile.png', fullPage: true });
    expect(await page.locator('body').innerText()).not.toContain('\u2014');
    expect(errors).toEqual([]);
});

